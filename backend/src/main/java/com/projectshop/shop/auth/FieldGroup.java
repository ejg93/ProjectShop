package com.projectshop.shop.auth;

/**
 * 응답에서 한 덩어리로 보이거나 가려지는 필드 묶음. 저장값은 {@code permission_field_group.code} 다.
 *
 * <p><b>이 인터페이스만 {@code auth} 에 있고 목록은 자원 패키지에 있다</b>(`11a` 와 같은 모양).
 * 반대로 두면 {@code auth} 가 자원마다 늘어나고 순환이 는다.
 *
 * <p><b>자원마다 목록이 다르므로 구현도 자원마다 하나다</b>(`D23` 「열거값을 어디에 두나」).
 * {@code basic} 이 주문에도 있고 사용자에도 있는데 뜻이 다르다 — 문자열로 두면
 * 주문 판정에 사용자 그룹을 물어도 컴파일이 통과하고 <b>조용히 거짓이 돌아온다.</b>
 *
 * <p>그 조용함이 이 타입을 만든 이유다. 오타나 잘못된 그룹은 {@code canSee} 가 {@code false} 를
 * 주고, 그러면 <b>응답에서 그 필드가 빠진다</b> — 막히는 쪽이라 안전하지만 오류도 로그도 안 남고,
 * 화면에서는 「볼 수 없는 필드」와 구분이 안 된다(`D20`).
 */
public interface FieldGroup {

    /** 저장값. DB 는 소문자다 */
    String code();
}
