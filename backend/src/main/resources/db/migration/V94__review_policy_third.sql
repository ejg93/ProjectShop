## 삭제 기준

다음 두 가지 경우에 후기가 내려갑니다.

1. **작성자가 직접 삭제한 경우.** 본인이 쓴 후기는 **내 정보 → 내 후기**에서 직접 삭제할 수 있습니다.
2. **신고가 접수되어 관리자가 아래 사유에 해당한다고 판단한 경우.**
   - 광고 또는 홍보 목적의 게시물
   - 욕설·비방 등 타인을 해치는 표현
   - 구매한 상품과 관련이 없는 내용
   - 다른 사람의 개인정보가 포함된 내용

셀러는 후기를 삭제할 수 없습니다. 답글로만 의견을 밝힐 수 있습니다.

