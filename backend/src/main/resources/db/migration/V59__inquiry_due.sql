-- 법정 요구의 처리 기한(청크 58-1).
--
-- 58 이 처리정지·이의제기를 받을 자리를 세우면서 **언제까지 답해야 하는지를 안 박았다** —
-- 조문을 원문으로 못 봤고 기억으로 박으면 틀린 날짜가 제약이 되기 때문이다.
-- 이번에 원문을 봤다.
--
--   개인정보 보호법 제37조      「지체 없이」 — **일수가 조문에 없다**
--   같은 법 시행령 제44조제2항  개인정보 처리정지 요구서를 **받은 날부터 10일 이내**에
--                               조치한 사실 또는 따르지 않은 사실·이유·이의제기방법을 알린다
--
-- 시행령 제41조제4항(열람)·제43조제3항(정정·삭제)도 같은 10일이다.
-- **달력일이다** — 「영업일」이라고 안 적혀 있어서 D10 의 영업일 계산이 안 걸린다.


-- 언제까지 답해야 하나. 박제한다.
--
-- **요구서를 받은 날에서 센다.** 답한 날에서 세면 늦게 답할수록 기한이 밀려서
-- 「늦었다」가 성립을 안 한다(refund.due_at 이 요청 시각이 아니라 사건 날에서 세는 것과 같다).
alter table inquiry add column due_at timestamptz;

comment on column inquiry.due_at is
    '법정 처리 기한. 처리정지는 접수일 + 10일이다(개인정보보호법 시행령 제44조제2항, D2 R28)';

-- 기존 행에 채운다. 처리정지 요구만 대상이다.
update inquiry
   set due_at = created_at + interval '10 days'
 where kind = 'processing_stop' and due_at is null;


-- **기한이 있는 종류에만 있다.**
--
-- 처리정지(제37조·시행령 제44조제2항)만 일수가 확인됐다. 나머지 셋은 안 박는다 —
-- 「안 넣은 것도 근거를 남긴다」(D23)라 여기 적는다.
--
--   access_objection  제38조제5항은 이의제기 절차를 마련하라고 하지 **기한을 안 준다**
--                     (원문에서 일수를 못 찾았다. 찾으면 이 제약에 값을 더한다)
--   dispute           전자상거래법이 「신속히」라고만 한다. 일수가 없다
--   product           법이 정한 기한이 없는 상품 문의다
--
-- **모르는 것을 지어서 박느니 비워 둔다.** 비어 있으면 「기한이 없다」고 읽히고,
-- 틀린 날짜가 박히면 그것이 지켜야 할 값이 된다.
alter table inquiry add constraint inquiry_due_at_check
    check ((kind = 'processing_stop') = (due_at is not null));

-- 기한을 넘긴 채 답이 안 나간 것을 찾는 자리.
--
-- **강제는 「넘긴 것이 조회로 드러난다」가 천장이다**(R5 가 환불 기한에서 적은 문장 그대로) —
-- 「기한 안에 답」을 check 로 못 건다: 막으면 늦은 답이 영영 안 나간다.
create index inquiry_overdue_idx on inquiry (due_at)
 where due_at is not null and status = 'received';
