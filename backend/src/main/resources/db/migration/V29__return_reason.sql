-- 반품 사유의 종류. 전자상거래법 제17조제1항과 제3항을 가른다(D2 R3).
--
-- 지금까지 반품 접수는 사유를 안 받았고, OrderStatusService 가 들어오는 것을 전부
-- 단순 변심으로 봤다. 그래서 8일째 하자 신고와 주문제작 상품의 하자가 거부됐다 —
-- 둘 다 법이 준 권리다.
--
--
-- 제3항이 「제1항 및 제2항에도 불구하고」로 시작한다. 그 한 마디가 둘을 동시에 연다.
--
--   제1항의 7일  →  공급받은 날부터 3개월 (그리고 안 날부터 30일)
--   제2항의 제한  →  안 걸린다. 복제 가능 상품이든 주문제작이든 하자면 철회할 수 있다
--
-- 청약철회 제한(제2항)은 「멀쩡한 물건을 무르는 것」을 막는 규정이라,
-- 물건이 약속과 다른 경우에는 애초에 적용될 자리가 아니다.
--
--
-- 제5항이 입증책임을 우리에게 지운다 — 「재화등의 훼손에 소비자의 책임이 있는지 여부 …
-- 다툼이 있는 경우에는 통신판매업자가 이를 증명하여야 한다」.
-- 그래서 접수 자체를 막지 않는다. 소비자가 하자라고 하면 3개월이 열리고, 다툼은 사후다.

alter table seller_order add column return_reason text;

-- 접수된 반품에만 있다. 접수 전이거나 다른 상태면 비어 있다.
--
-- 값을 닫는다(D23 「법이 인정한 목록은 닫는다」). 자유 텍스트로 두면
-- 어느 조항으로 접수된 것인지가 판정에 안 쓰이고, 그러면 기한이 갈리지 않는다.
--
--   change_of_mind  제17조제1항. 7일, 제한 사유가 걸린다
--   defect          제17조제3항. 3개월, 제한 사유가 안 걸린다
alter table seller_order add constraint seller_order_return_reason_check
    check (return_reason is null or return_reason in ('change_of_mind', 'defect'));

comment on column seller_order.return_reason is
    '반품 사유의 종류. 제17조제1항과 제3항을 가른다 — 기한과 제한 적용이 달라진다(D2 R3)';

-- 사유가 없는 반품 접수를 막는다.
--
-- 「접수됐는데 왜인지 모르는」 행은 어느 조항으로 받은 것인지 판정이 안 서고,
-- 반품 비용 부담(제18조제9항·제10항)도 못 가른다.
--
-- returned 에는 안 건다. 정상 경로는 접수를 지나므로 그때 채워진 값이 그대로 남는데,
-- 관리자가 표 밖으로 옮기는 경로가 접수를 건너뛰고 반품완료로 직행할 수 있다(D7).
-- 그 경우는 접수 자체가 없었으므로 조항도 없는 것이 사실이고, 왜 그랬는지는
-- order_status_history.reason 에 남는다 — 관리자 강제 전이는 사유가 필수다(V18).
--
-- returned 에도 걸면 CS 처리가 막힌다. 사실 아닌 값을 채워 넣게 만드는 제약은
-- 데이터를 지키는 것이 아니라 거짓말을 강요하는 것이다.
alter table seller_order add constraint seller_order_return_reason_required_check
    check (status <> 'return_requested' or return_reason is not null);


-- 기한을 안 박제한다.
--
-- withdrawal_expire_at·auto_confirm_at 을 박제한 근거는 D10 의 「임시공휴일이 나중에
-- 추가되면 지난 기한까지 흔들린다」였다. 영업일 계산이 달력을 타서 그렇다.
--
-- 제17조제3항의 3개월은 역일이라 그 문제가 없다. delivered_at 에서 세면 언제 계산해도
-- 같은 값이 나온다 — 박제할 이유가 없는데 박제하면 같은 사실이 두 곳에 생긴다(사용자 선택).
--
--
-- 「안 날 또는 알 수 있었던 날부터 30일」은 안 건다.
--
-- 그 날은 소비자의 인식이라 우리가 관찰할 수 없다. 접수 화면에서 받는 방법도 있지만
-- 소비자가 자기에게 불리한 날짜를 적을 이유가 없어서 거르는 힘이 없고,
-- 제17조제5항이 입증책임을 우리에게 지운 마당에 소비자 진술로 권리를 자르는 모양이 된다.
--
-- 짧게 지는 쪽이 안전한 방향이다 — 3개월만 보면 우리가 더 받아 주는 것이고,
-- 30일을 우리가 계산해서 자르면 그것이 틀렸을 때 권리를 뺏은 것이 된다.
-- 안 건 것이지 빠뜨린 것이 아니라는 근거를 D2 R3 에 적었다.
