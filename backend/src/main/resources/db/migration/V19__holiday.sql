-- 공휴일. 영업일 계산이 이 표를 본다(D10).
--
-- 코드에 박지 않는 이유는 임시공휴일 때문이다. 선거일과 국가 지정 임시공휴일은
-- 그해에 정해져서, 코드에 두면 그때마다 배포해야 한다.
--
-- 토·일은 안 넣는다. 요일은 날짜에서 나오므로 표에 담으면 같은 사실이 두 곳에 있게 된다.
--
-- 영업일 계산이 필요한 자리는 둘뿐이다(D10) — 기한의 말일 보정과 정산 지급일.
-- 그 밖의 기간은 역일로 센다. 넓게 쓰면 이 표가 빈 연도에서 결과가 조용히 틀린다.

create table holiday (
    -- 값 자체가 식별자다(D22). 대리키를 얹으면 아무도 안 쓰는 번호가 생기고,
    -- "같은 날이 두 번 들어가면 안 된다" 를 유니크 제약으로 따로 적게 된다.
    holiday_date date not null primary key,

    name text not null,

    created_at timestamptz not null default now()
);

comment on table holiday is '영업일이 아닌 날. 토·일은 요일로 판단하므로 여기 없다(D10)';


