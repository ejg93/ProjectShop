-- 탈퇴 유예를 30일에서 5일로 줄인 것을 방침에 반영한다(Q10, D2 R9).
--
-- 개인정보법 제21조제1항은 「불필요하게 되었을 때에는 **지체 없이** 파기」고,
-- 단서가 인정하는 예외는 **「다른 법령에 따라 보존하여야 하는 경우」 하나뿐**이다.
-- 「실수로 탈퇴한 사람의 복구」는 법령이 아니라 우리 편의였다.
-- 표준 개인정보 보호지침 제10조제1항이 그 「지체 없이」를 근무일 기준 5일로 본다.
--
--
-- **본문을 다시 안 적는다.** 지금 판을 읽어서 두 줄만 바꾼 새 판을 넣는다.
-- 통째로 베끼면 그 사이 다른 청크가 고친 문안이 조용히 되돌아간다 —
-- `D2-4` 가 이미 약관 문안을 한 번 고쳤고, 앞으로도 고친다.
--
-- 시행된 판은 못 고친다(policy_document_immutable). 개정은 언제나 새 판이다.
--
--
-- **시행일이 7일 뒤다.** 개인정보 보호법 시행령 제31조제3항이 변경 사항을 미리 알리라고 한다(R11).
--
-- 그런데 **코드는 오늘부터 5일로 지운다.** 그 사이 이레 동안 방침은 30일이라 말하고
-- 실제로는 더 일찍 지운다 — 그 방향을 고른 이유가 둘이다.
--
--   1. 제21조는 법률이고 제31조제3항은 시행령의 고지 의무다. 파기를 미루는 쪽이 더 무겁다
--   2. **덜 보관하는 방향이라 이용자에게 불리하지 않다.** 반대였다면(5일 → 30일) 고지가 먼저여야 한다
insert into policy_document (code, version, title, body, effective_at)
select code,
       version + 1,
       title,
       replace(
           replace(body,
                   '| 회원 정보 | 탈퇴 후 30일 | 실수로 탈퇴하신 경우의 복구 기간 |',
                   '| 회원 정보 | 탈퇴 후 5일 | 실수로 탈퇴하신 경우의 복구 기간 |'),
           '탈퇴하시면 30일이 지난 뒤 이메일, 이름, 비밀번호를 지웁니다.',
           '탈퇴하시면 5일이 지난 뒤 이메일, 이름, 비밀번호를 지웁니다.'),
       now() + interval '7 days'
  from policy_document
 where code = 'privacy_policy'
 order by effective_at desc, version desc
 limit 1;
