## 2. 청약철회가 제한되는 경우

아래에 해당하면 청약철회가 제한됩니다. (같은 법 제17조제2항)

1. 이용자의 책임으로 상품이 없어지거나 훼손된 경우.
   **다만 내용을 확인하기 위하여 포장을 뜯으신 경우는 제외합니다.**
2. 사용하시거나 일부 소비하여 상품의 가치가 뚜렷하게 줄어든 경우
3. 시간이 지나 다시 판매하기 어려울 정도로 가치가 뚜렷하게 줄어든 경우
4. 복제가 가능한 상품의 포장을 훼손한 경우
5. 주문에 따라 개별적으로 생산되는 상품 등, 청약철회를 인정하면 판매자에게 회복할 수 없는
   손해가 예상되어 미리 알려 드리고 동의를 받은 경우

**제한되는 상품은 주문하시기 전에 상품 상세 화면에 표시합니다.**
표시하지 않은 상품은 위에 해당하더라도 청약철회를 제한하지 않습니다.

