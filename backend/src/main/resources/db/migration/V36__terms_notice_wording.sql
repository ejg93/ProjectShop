## 제1조 (목적)

이 약관은 회사가 운영하는 통신판매중개 서비스의 이용 조건을 정합니다.

## 제2조 (중개자의 지위)

**회사는 통신판매중개자이며 통신판매의 당사자가 아닙니다.**
상품의 판매 주체는 각 판매자입니다.

**다만 회사가 대금을 직접 받고 주문을 접수하므로, 법이 정한 아래 책임은 회사도 집니다.**
(전자상거래법 제20조의2, 제20조의3, 제18조제11항)

## 제3조 (누가 무엇을 책임지나)

| 무엇 | 누가 |
|---|---|
| 상품의 내용과 품질, 하자 | 판매자 |
| 배송과 반품 물류 | 판매자 |
| **대금의 환급** | **판매자와 회사가 함께** |
| **청약 접수의 확인** | **회사** |
| **거래조건의 표시와 계약내용의 교부** | **회사** |
| **불만과 분쟁 처리에 필요한 조치** | **회사** |

**회사가 중개자라는 이유로 위 책임을 면하지 않습니다.**

## 제4조 (청약철회)

**상품을 받은 날부터 7일 이내에 청약철회를 할 수 있습니다.**
다만 법이 정한 사유에 해당하면 철회가 제한되며, 제한되는 상품은 주문 전에 표시합니다.

상품이 표시·광고와 다르거나 계약과 다르게 배송된 경우에는 기간이 따로 있습니다.
자세한 내용은 청약철회 안내에서 확인하실 수 있습니다.

## 제5조 (구매확정과 자동 구매확정)

구매하신 상품에 이상이 없으면 구매확정을 하실 수 있습니다.

**배송이 완료된 날부터 8일이 지날 때까지 구매확정도 반품 신청도 하지 않으시면,
그 상품을 구매확정하신 것으로 봅니다.** 이 기간은 청약철회 기간이 끝난 다음 날보다
빨리 오지 않으며, 정확한 날짜는 주문 상세에서 미리 확인하실 수 있습니다.

구매확정 뒤에는 청약철회를 하실 수 없습니다.
상품에 하자가 있거나 표시·광고와 다른 경우는 제4조의 기간이 따로 적용됩니다.

## 제6조 (회원 탈퇴)

회원은 언제든지 탈퇴할 수 있습니다. 탈퇴 후 5일이 지나면 개인정보를 파기합니다.
다만 법령이 보존을 요구하는 거래기록은 그 기간 동안 보관하며,
그 안의 개인정보는 파기 시점에 함께 지웁니다.
